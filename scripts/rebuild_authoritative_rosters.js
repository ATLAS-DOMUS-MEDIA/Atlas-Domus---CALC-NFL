const allRosters = {};
const flatPlayers = [];

for (const team of TEAMS_DATA) {
  const teamAbbr = team.id;
  allRosters[teamAbbr] = [];

  for (const p of team.players) {
    const isOut = p.status === 'Out' || (p.injury && p.injury.toLowerCase().includes('out'));
    const athlete = {
      name: p.name,
      jersey: p.jersey || null,
      position: p.pos,
      team: teamAbbr,
      experience: p.exp || 1,
      status: isOut ? 'inactive' : 'active',
      injury: p.injury || null,
      is_active_today: !isOut,
    };
    allRosters[teamAbbr].push(athlete);

    flatPlayers.push({
      id: `nfl_${teamAbbr.toLowerCase()}_${p.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}`,
      name: p.name,
      team_id: teamAbbr,
      position: p.pos,
      jersey_number: p.jersey ? parseInt(p.jersey, 10) : null,
      years_exp: p.exp || 1,
      status: isOut ? 'Out' : 'Active',
      is_active_today: !isOut,
      injury_designation: isOut ? (p.injury || 'Out') : 'None',
      inactive_reason: p.inactive_reason || (isOut ? `Lesão: ${p.injury || 'Out'}` : null),
    });
  }
}

